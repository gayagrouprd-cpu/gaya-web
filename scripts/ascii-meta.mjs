#!/usr/bin/env node
// T20 de DIRECTION §13 (datos estructurados y metadatos) y SEO de §10 sobre lo CONSTRUIDO en dist/, sin navegador:
//   · <html lang>, un solo <title> y <h1>, descripción de longitud razonable;
//   · canonical absoluto y propio; hreflang es / en / x-default, absolutos, con el par RECÍPROCO (la página en español apunta a la inglesa
//     y la inglesa a la española, cada una con su propio idioma) y el mismo conjunto en sitemap.xml;
//   · Open Graph y Twitter: og:url = canonical, og:image absoluta, que EXISTE en dist/, es JPEG de 1200×630, pesa ≤ 300 KB y no lleva en sus
//     bytes metadatos de una herramienta de generación (Claude, OpenAI, Midjourney…; la regla R3: la web nunca dice que la hizo una IA);
//   · JSON-LD parseable, con @context de schema.org, Organization + Service, sin LocalBusiness ni valoraciones;
//   · robots.txt apunta al sitemap; los enlaces internos «#ancla» de las portadas resuelven a un id existente; los h2 y h3 de las portadas
//     llevan id (enlazables).
// Uso: node scripts/ascii-meta.mjs [--dir dist]
import { existsSync, readFileSync, statSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const di = process.argv.indexOf('--dir');
const dist = join(ROOT, di > -1 ? process.argv[di + 1] : 'dist');
const SITE = 'https://gaya.com.do';

const PAGES = [
  { file: 'index.html', path: '/', lang: 'es', other: '/en/', home: true },
  { file: 'en/index.html', path: '/en/', lang: 'en', other: '/', home: true },
];
const failures = [];
let checks = 0;
const check = (ok, msg) => {
  checks++;
  if (!ok) {
    failures.push(msg);
    console.log(`FALLA ${msg}`);
  }
  return ok;
};

const attr = (tag, name) => new RegExp(`\\b${name}="([^"]*)"`).exec(tag)?.[1];
const tags = (html, re) => [...html.matchAll(re)].map((m) => m[0]);
const meta = (html, key, val) => tags(html, /<meta\b[^>]*>/g).find((t) => attr(t, key) === val);
const FORBIDDEN_TOOLS = /claude|anthropic|openai|chatgpt|gpt-?\d|midjourney|dall-?e|stable ?diffusion|firefly|gemini|copilot|generated by|ai[- ]generated|generado (?:con|por) (?:ia|inteligencia)/i;

const info = {};
for (const p of PAGES) {
  const file = join(dist, p.file);
  if (!check(existsSync(file), `${p.file}: no existe en dist/ (¿falta «npm run build»?)`)) continue;
  const html = readFileSync(file, 'utf8');
  const where = p.path;
  check(attr(/<html\b[^>]*>/.exec(html)?.[0] ?? '', 'lang') === p.lang, `${where}: <html lang> distinto de ${p.lang}`);
  const titles = html.match(/<title>[^<]*<\/title>/g) ?? [];
  check(titles.length === 1, `${where}: ${titles.length} etiquetas <title>`);
  const title = (titles[0] ?? '').replace(/<\/?title>/g, '');
  check(title.length >= 10 && title.length <= 70, `${where}: título de ${title.length} caracteres (10–70)`);
  const desc = attr(meta(html, 'name', 'description') ?? '', 'content') ?? '';
  check(desc.length >= 50 && desc.length <= 170, `${where}: descripción de ${desc.length} caracteres (50–170)`);
  check((html.match(/<h1\b/g) ?? []).length === 1, `${where}: debe haber exactamente un <h1>`);

  // canonical + hreflang
  const canon = tags(html, /<link\b[^>]*rel="canonical"[^>]*>/g);
  check(canon.length === 1 && attr(canon[0], 'href') === SITE + p.path, `${where}: canonical debe ser ${SITE + p.path} (es ${canon.map((c) => attr(c, 'href')).join(', ') || 'ninguno'})`);
  const alt = Object.fromEntries(tags(html, /<link\b[^>]*rel="alternate"[^>]*hreflang="[^"]*"[^>]*>/g).map((t) => [attr(t, 'hreflang'), attr(t, 'href')]));
  info[p.path] = alt;
  const mine = p.lang;
  const theirs = p.lang === 'es' ? 'en' : 'es';
  check(alt[mine] === SITE + p.path, `${where}: hreflang=${mine} debe apuntar a sí misma (${alt[mine]})`);
  check(alt[theirs] === SITE + p.other, `${where}: hreflang=${theirs} debe apuntar a ${SITE + p.other} (${alt[theirs]})`);
  check(alt['x-default'] === SITE + PAGES.find((q) => q.lang === 'es' && q.home === p.home).path, `${where}: x-default debe ser la versión en español (${alt['x-default']})`);

  // Open Graph / Twitter
  const og = (k) => attr(meta(html, 'property', `og:${k}`) ?? '', 'content');
  check(og('url') === SITE + p.path, `${where}: og:url debe ser el canonical (${og('url')})`);
  check(!!og('title') && !!og('description') && og('type') === 'website', `${where}: faltan og:title, og:description u og:type`);
  check(!!og('locale'), `${where}: falta og:locale`);
  check(attr(meta(html, 'name', 'twitter:card') ?? '', 'content') === 'summary_large_image', `${where}: twitter:card debe ser summary_large_image`);
  const img = og('image');
  if (check(!!img && img.startsWith(SITE + '/'), `${where}: og:image debe ser absoluta en ${SITE} (${img})`)) {
    const f = join(dist, img.slice(SITE.length));
    if (check(existsSync(f), `${where}: og:image no existe en dist/ (${img})`)) {
      const buf = readFileSync(f);
      const m = await sharp(buf).metadata();
      check(m.format === 'jpeg' && m.width === 1200 && m.height === 630, `${img}: debe ser JPEG de 1200×630 (es ${m.format} ${m.width}×${m.height})`);
      check(statSync(f).size <= 300 * 1024, `${img}: pesa ${(statSync(f).size / 1024).toFixed(0)} KB (> 300)`);
      const text = buf.toString('latin1');
      check(!FORBIDDEN_TOOLS.test(text), `${img}: sus bytes mencionan una herramienta de generación (${FORBIDDEN_TOOLS.exec(text)?.[0]})`);
    }
  }
  check(!FORBIDDEN_TOOLS.test(`${title} ${desc} ${og('title')} ${og('description')}`), `${where}: el título o las descripciones mencionan una herramienta de IA`);

  // JSON-LD
  const lds = [...html.matchAll(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/g)].map((m) => m[1]);
  if (p.home) {
    check(lds.length >= 1, `${where}: falta el JSON-LD`);
    for (const raw of lds) {
      let data;
      try {
        data = JSON.parse(raw);
      } catch (e) {
        check(false, `${where}: JSON-LD no parsea (${e.message})`);
        continue;
      }
      const nodes = Array.isArray(data) ? data : data['@graph'] ?? [data];
      const types = nodes.flatMap((n) => [].concat(n['@type'] ?? []));
      check(String(data['@context'] ?? nodes[0]?.['@context']).includes('schema.org'), `${where}: JSON-LD sin @context de schema.org`);
      check(types.includes('Organization'), `${where}: JSON-LD sin Organization (${types.join(', ')})`);
      check(types.filter((t) => t === 'Service').length === 4, `${where}: JSON-LD debe traer 4 Service (trae ${types.filter((t) => t === 'Service').length})`);
      check(!types.includes('LocalBusiness'), `${where}: JSON-LD con LocalBusiness (no corresponde a una marca personal sin local)`);
      check(!/aggregateRating|"review"|ratingValue/.test(raw), `${where}: JSON-LD con valoraciones o reseñas (no hay clientes que las respalden)`);
      check(!FORBIDDEN_TOOLS.test(raw), `${where}: JSON-LD menciona una herramienta de IA`);
    }
    // enlaces internos y títulos enlazables
    const ids = new Set([...html.matchAll(/\bid="([^"]+)"/g)].map((m) => m[1]));
    const broken = [...new Set([...html.matchAll(/\bhref="#([^"]+)"/g)].map((m) => m[1]))].filter((a) => !ids.has(a));
    check(broken.length === 0, `${where}: anclas internas sin destino: ${broken.join(', ')}`);
    const noId = tags(html, /<h[23]\b[^>]*>/g).filter((t) => !attr(t, 'id'));
    check(noId.length === 0, `${where}: ${noId.length} h2/h3 sin id (no se pueden enlazar)`);
  }
}

// reciprocidad entre las dos portadas
for (const [a, b] of [['/', '/en/']]) {
  if (!info[a] || !info[b]) continue;
  check(info[a].en === info[b].en && info[a].es === info[b].es && info[a]['x-default'] === info[b]['x-default'], `hreflang no recíproco entre ${a} y ${b}: ${JSON.stringify(info[a])} frente a ${JSON.stringify(info[b])}`);
}

// la galería vieja ya no es una página: redirige a la sección de ejemplos de la portada, no se indexa y no entra en el sitemap
const smXml = existsSync(join(dist, 'sitemap.xml')) ? readFileSync(join(dist, 'sitemap.xml'), 'utf8') : '';
for (const [file, path, to, canonical] of [
  ['referencias/index.html', '/referencias/', '/#ejemplos', SITE + '/'],
  ['en/references/index.html', '/en/references/', '/en/#samples', SITE + '/en/'],
]) {
  const f = join(dist, file);
  if (!check(existsSync(f), `${path}: falta la página que redirige a ${to}`)) continue;
  const html = readFileSync(f, 'utf8');
  check(html.includes(`http-equiv="refresh" content="0; url=${to}"`), `${path}: no redirige a ${to}`);
  check(/name="robots" content="noindex/.test(html), `${path}: sin noindex`);
  check(html.includes(`rel="canonical" href="${canonical}"`), `${path}: canonical distinto de ${canonical}`);
  check(!smXml.includes(`<loc>${SITE + path}</loc>`), `sitemap.xml lista ${SITE + path} (solo redirige)`);
}

// sitemap y robots
const sm = join(dist, 'sitemap.xml');
if (check(existsSync(sm), 'sitemap.xml no existe')) {
  const xml = readFileSync(sm, 'utf8');
  const locs = [...xml.matchAll(/<loc>([^<]+)<\/loc>/g)].map((m) => m[1]);
  for (const p of PAGES) check(locs.includes(SITE + p.path), `sitemap.xml no lista ${SITE + p.path}`);
  check(new Set(locs).size === locs.length, 'sitemap.xml repite alguna URL');
  const block = (loc) => xml.split('<url>').find((u) => u.includes(`<loc>${loc}</loc>`)) ?? '';
  for (const loc of [SITE + '/', SITE + '/en/']) check(/hreflang="es"/.test(block(loc)) && /hreflang="en"/.test(block(loc)), `sitemap.xml: ${loc} sin su par hreflang es/en`);
}
const robots = join(dist, 'robots.txt');
check(existsSync(robots) && /Sitemap:\s*https:\/\/gaya\.com\.do\/sitemap\.xml/.test(readFileSync(robots, 'utf8')), 'robots.txt debe apuntar a sitemap.xml');

console.log(`\n${checks - failures.length}/${checks} comprobaciones de metadatos en verde (T20).`);
console.log('T20 deja fuera, a propósito: el validador externo de schema.org (no hay terceros: lo cubre scripts/lint-content.mjs con las propiedades permitidas por tipo).');
process.exit(failures.length ? 1 : 0);
